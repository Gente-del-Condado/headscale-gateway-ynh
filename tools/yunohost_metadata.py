#!/usr/bin/env python3
"""Genera la presentación del paquete a partir de sus metadatos y descripción."""
from pathlib import Path
import tomllib

ROOT = Path(__file__).resolve().parents[1]


def readme(root=ROOT):
    source = root / 'packaging/yunohost'
    manifest = tomllib.loads((source / 'manifest.toml').read_text())
    description = (source / 'doc/DESCRIPTION.md').read_text().strip()
    return f'''<!-- This README was automatically generated by tools/yunohost_metadata.py.
Structure follows https://github.com/YunoHost/apps_tools/tree/main/readme_generator.
Edit manifest.toml, doc/DESCRIPTION.md and doc/ADMIN.md; do not edit this file. -->

# {manifest['name']} for YunoHost

{manifest['description']['en']}

**Package version:** {manifest['version']} · **License:** {manifest['upstream']['license']}

{description}

## Install and upgrade

The catalog request is being prepared. Installation from a custom URL does not
mean the package has been accepted into the official catalog.

```bash
sudo yunohost app install https://github.com/Gente-del-Condado/headscale-gateway_ynh
sudo yunohost app upgrade headscale_gateway --url https://github.com/Gente-del-Condado/headscale-gateway_ynh
```

## Documentation and support

- [Installation, SSO, upgrade, backup and restoration](doc/ADMIN.md)
- [Complete web manual](https://gente-del-condado.github.io/headscale-gateway_ynh/)
- [Package issues](https://github.com/Gente-del-Condado/headscale-gateway_ynh/issues)
- [Catalog entry, available after approval](https://apps.yunohost.org/app/headscale_gateway)

The full server build sources are in `payload/source.tar.gz`, including Go
dependencies, build instructions and checksums. Third-party notices are in
`payload/notices/`. Build sources for other platforms are documented in the manual.

## En español

{manifest['description']['es']}. Consulta [la guía de administración](doc/ADMIN.md)
y el [manual web](https://gente-del-condado.github.io/headscale-gateway_ynh/).
'''


if __name__ == '__main__':
    (ROOT / 'packaging/yunohost/README.md').write_text(readme())
